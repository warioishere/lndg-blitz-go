-- Paths the route scout verified to nodes of the network: a probe reached the
-- node, which rejected the unknown payment, so every channel on the way carried
-- the amount. The rebalancer combines them with saved routes into refill
-- routes. Rows older than 7 days are deleted.
CREATE TABLE scout_path (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_pubkey    character varying(66) NOT NULL,
    outgoing_chan_id character varying(20) NOT NULL,
    route            text NOT NULL,
    route_hex        text NOT NULL,
    value_sat        bigint NOT NULL,
    last_verified    timestamp with time zone NOT NULL,
    UNIQUE (target_pubkey, outgoing_chan_id, route)
);
CREATE INDEX scout_path_verified_idx ON scout_path (last_verified);

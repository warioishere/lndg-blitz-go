-- Routing policies on all channels of our peers, from gossip updates and a
-- daily snapshot of the graph: the market around each peer (what other nodes
-- charge toward it, which of their channels are disabled or announce a small
-- max_htlc). One row per policy change of policy_node on chan_id; peer_pubkey
-- is the peer of ours on that channel. No gui_ prefix: a Go-only table.
CREATE TABLE market_policy (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"       timestamp with time zone NOT NULL,
    source            character varying(8) NOT NULL,
    chan_id           character varying(20) NOT NULL,
    capacity          bigint NOT NULL,
    peer_pubkey       character varying(66) NOT NULL,
    policy_node       character varying(66) NOT NULL,
    fee_ppm           bigint NOT NULL,
    base_fee_msat     bigint NOT NULL,
    inbound_fee_ppm   integer NOT NULL,
    inbound_base_msat integer NOT NULL,
    min_htlc_msat     bigint NOT NULL,
    max_htlc_msat     bigint NOT NULL,
    time_lock_delta   integer NOT NULL,
    disabled          boolean NOT NULL,
    last_update       timestamp with time zone
);
CREATE INDEX market_policy_peer_ts_idx ON market_policy (peer_pubkey, "timestamp");
CREATE INDEX market_policy_ts_idx ON market_policy ("timestamp");

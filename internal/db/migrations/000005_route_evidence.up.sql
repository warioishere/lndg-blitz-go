-- When the route prober last verified a route and for how many sats, so the
-- rebalancer can rank routes by their latest evidence. Routes that were never
-- paid get a verification time 2 hours back: outside the fresh window, and
-- removed after 24 hours unless the prober verifies them again.
ALTER TABLE gui_rebalanceroute
    ADD COLUMN last_probed timestamp with time zone,
    ADD COLUMN probed_amount_sat bigint;
UPDATE gui_rebalanceroute SET last_probed = now() - interval '2 hours'
WHERE success_count = 0 AND failure_count = 0;

-- One row per saved route the rebalancer tried, with the list it came from
-- (proven, explore, failed), its position and the outcome, to evaluate the
-- route ranking. No gui_ prefix: a Go-only table the Django app does not know.
CREATE TABLE route_attempt_log (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"      timestamp with time zone NOT NULL,
    rebalance_id     bigint NOT NULL,
    route_id         bigint NOT NULL,
    target_pubkey    character varying(66) NOT NULL,
    outgoing_chan_id character varying(20) NOT NULL,
    list             character varying(10) NOT NULL,
    position         integer NOT NULL,
    evidence_age_s   double precision,
    fee_ppm          double precision,
    value_sat        bigint NOT NULL,
    outcome          character varying(20) NOT NULL,
    failure_code     integer,
    failure_hop      integer
);
CREATE INDEX route_attempt_log_ts_idx ON route_attempt_log ("timestamp");

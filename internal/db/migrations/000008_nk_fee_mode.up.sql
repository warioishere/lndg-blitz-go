-- NK fee mode: a per-channel alternative to auto-fees modelled on the fee
-- algorithm a peer operator described (fill target per channel, percent steps,
-- no decrease after large outbound flow, anchor on the price the channel
-- actually sold at). af_mode 'nk' hands the channel's outbound fee, inbound
-- discount and max_htlc to the NK job; nk_target is its local liquidity target
-- in percent (NULL: 100 - ar_in_target); nk_budget makes the rebalancer use the
-- NK budget for it. nk_last_change / nk_last_publish pace the policy updates.
ALTER TABLE gui_channels
    ADD COLUMN af_mode character varying(8) NOT NULL DEFAULT 'lndg',
    ADD COLUMN nk_target integer,
    ADD COLUMN nk_budget boolean NOT NULL DEFAULT false,
    ADD COLUMN nk_last_change timestamp with time zone,
    ADD COLUMN nk_last_publish timestamp with time zone;

-- One row per NK decision: applied on NK channels, shadow (not applied) on the
-- other auto-fee channels. No gui_ prefix: a Go-only table.
CREATE TABLE nk_fee_log (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"   timestamp with time zone NOT NULL,
    chan_id       character varying(20) NOT NULL,
    peer_alias    character varying(32) NOT NULL,
    applied       boolean NOT NULL,
    reason        character varying(40) NOT NULL,
    local_pct     double precision NOT NULL,
    target_pct    integer NOT NULL,
    flow24_ppm    integer,
    flow72_ppm    integer,
    lock_until    timestamp with time zone,
    fee_old       integer NOT NULL,
    fee_new       integer NOT NULL,
    cap_ppm       integer NOT NULL,
    max_htlc_old  bigint NOT NULL,
    max_htlc_new  bigint NOT NULL,
    inbound_old   integer NOT NULL,
    inbound_new   integer NOT NULL
);
CREATE INDEX nk_fee_log_chan_ts_idx ON nk_fee_log (chan_id, "timestamp");
CREATE INDEX nk_fee_log_ts_idx ON nk_fee_log ("timestamp");

-- The NK flow query reads a channel's balance-outs of the last 72 hours.
CREATE INDEX payments_chan_out_date_idx ON gui_payments (chan_out, creation_date);

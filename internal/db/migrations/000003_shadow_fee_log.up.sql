-- What a fee rule in shadow mode would have set, with the inputs it decided on,
-- so the rule can be evaluated (also with other margins) before it is activated.
-- No gui_ prefix: a Go-only table the Django app does not know.
CREATE TABLE shadow_fee_log (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"            timestamp with time zone NOT NULL,
    rule                   character varying(20) NOT NULL,
    chan_id                character varying(20) NOT NULL,
    peer_alias             character varying(32) NOT NULL,
    local_fee_rate         integer NOT NULL,
    local_inbound_fee_rate integer NOT NULL,
    avg_rebalance_cost     integer NOT NULL,
    out_percent            integer NOT NULL,
    hours_since_out        double precision,
    current_value          integer NOT NULL,
    proposed_value         integer NOT NULL
);
CREATE INDEX shadow_fee_log_ts_idx ON shadow_fee_log ("timestamp");
